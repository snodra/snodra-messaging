package com.damoreira.snodra.examples.a

import com.damoreira.snodra.messaging.AccessDeniedException
import com.damoreira.snodra.messaging.api.MessageType
import com.damoreira.snodra.messaging.handler.QueryHandler
import com.damoreira.snodra.messaging.test.InMemoryBuses
import org.assertj.core.api.Assertions.assertThat
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.test.context.TestConfiguration
import org.springframework.boot.webmvc.test.autoconfigure.WebMvcTest
import org.springframework.context.annotation.Bean
import org.springframework.context.annotation.Import
import org.springframework.http.HttpStatus
import org.springframework.test.annotation.DirtiesContext
import org.springframework.test.web.servlet.assertj.MockMvcTester
import kotlin.test.Test

@WebMvcTest(ForbiddenSendController::class)
@Import(ForbiddenSendControllerTest.Buses::class)
@DirtiesContext(classMode = DirtiesContext.ClassMode.AFTER_EACH_TEST_METHOD)
class ForbiddenSendControllerTest {
    @TestConfiguration
    class Buses {
        @Bean fun inMemoryBuses() = InMemoryBuses(typePrefix = "service-a")
    }

    /** Stands in for the hub's access control: a type outside the token's `send` patterns is answered PERMISSION_DENIED. */
    class DenyingHub {
        @QueryHandler
        fun handle(q: ForbiddenProbe): ForbiddenProbeAnswer = throw AccessDeniedException("type examples.ForbiddenProbe is not allowed to send")
    }

    /** Stands in for a hub without access control and an owner of the probe. */
    class Owner {
        @QueryHandler
        fun handle(q: ForbiddenProbe) = ForbiddenProbeAnswer("answered")
    }

    @Autowired lateinit var mvc: MockMvcTester
    @Autowired lateinit var buses: InMemoryBuses

    @Test fun `a send the hub refuses answers 403 with the exception name`() {
        buses.register(DenyingHub())
        assertThat(mvc.get().uri("/forbidden-send"))
            .hasStatus(HttpStatus.FORBIDDEN)
            .bodyJson().isLenientlyEqualTo("""{"error":"AccessDeniedException"}""")
    }

    @Test fun `a send the hub allows returns the answer`() {
        buses.register(Owner())
        assertThat(mvc.get().uri("/forbidden-send"))
            .hasStatus(HttpStatus.OK)
            .bodyJson().isLenientlyEqualTo("""{"note":"answered"}""")
    }

    @Test fun `the probe type is deliberately not one the sandbox ACL lists`() {
        // The ACL generated by infra/scripts/dev-hub-pki.sh lists service-a's send patterns by exact name; the probe
        // must stay outside all of them for step 21 of the smoke to see a refusal.
        assertThat(ForbiddenProbe::class.java.getAnnotation(MessageType::class.java).value).isEqualTo("examples.ForbiddenProbe")
    }
}
